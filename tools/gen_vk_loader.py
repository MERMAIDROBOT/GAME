"""Generate runtime/gpu/third_party/vk_loader/{volk.h,volk.c}: the small subset of the volk API the GPU renderer
uses (volkInitialize, volkInitializeCustom, volkLoadInstance), holding a pointer for each Vulkan function the
renderer calls. Device functions load through vkGetInstanceProcAddr and dispatch by handle, as with volk's
volkLoadInstance, so two devices can coexist. Generated from the vendored headers and the renderer's own source,
so the build fetches nothing.

Usage: python3 tools/gen_vk_loader.py [--check]   (--check fails if the committed files are stale)"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
GPU = ROOT / 'runtime/gpu'
HEADERS = GPU / 'third_party/vulkan-headers/include/vulkan'
OUT = GPU / 'third_party/vk_loader'
SCAN = ['src', 'host-adapter', 'native-plugin', 'include', 'host-model']
# Platform headers and the macro vulkan.h needs before it declares their functions.
GUARDS = {'vulkan_core.h': None, 'vulkan_metal.h': 'VK_USE_PLATFORM_METAL_EXT', 'vulkan_macos.h': 'VK_USE_PLATFORM_MACOS_MVK',
          'vulkan_ios.h': 'VK_USE_PLATFORM_IOS_MVK', 'vulkan_win32.h': 'VK_USE_PLATFORM_WIN32_KHR',
          'vulkan_xlib.h': 'VK_USE_PLATFORM_XLIB_KHR', 'vulkan_xcb.h': 'VK_USE_PLATFORM_XCB_KHR',
          'vulkan_wayland.h': 'VK_USE_PLATFORM_WAYLAND_KHR', 'vulkan_android.h': 'VK_USE_PLATFORM_ANDROID_KHR',
          'vulkan_beta.h': 'VK_ENABLE_BETA_EXTENSIONS'}
GLOBAL = ('vkCreateInstance', 'vkEnumerateInstanceExtensionProperties', 'vkEnumerateInstanceLayerProperties',
          'vkEnumerateInstanceVersion')


def declared():
    where = {}
    for header, guard in GUARDS.items():
        path = HEADERS / header
        if path.exists():
            for name in re.findall(r'typedef \w[\w\s\*]* \(VKAPI_PTR \*PFN_(vk\w+)\)', path.read_text()):
                where.setdefault(name, guard)
    return where


def used(known):
    names = set()
    for folder in SCAN:
        for path in (GPU / folder).rglob('*'):
            if path.suffix in {'.cpp', '.h', '.hpp', '.c', '.inl'} and 'third_party' not in path.parts:
                names |= set(re.findall(r'\b(vk[A-Z]\w+)\b', path.read_text(errors='replace')))
    return sorted((names & set(known)) | {'vkGetInstanceProcAddr', *GLOBAL} & set(known))


def render():
    known = declared(); names = used(known)
    groups = {}
    for name in names:
        groups.setdefault(known[name], []).append(name)

    def guarded(lines_for):
        out = []
        for guard in sorted(groups, key=lambda g: (g is not None, g or '')):
            body = [lines_for(n) for n in groups[guard]]
            out += ([f'#if defined({guard})'] if guard else []) + body + (['#endif'] if guard else [])
        return '\n'.join(out)

    header = f'''// Generated by tools/gen_vk_loader.py from the vendored Vulkan headers and the renderer's source. Do not edit.
// The volk API subset the GPU renderer uses; the build defines VK_NO_PROTOTYPES for every user.
#pragma once
#ifndef VK_NO_PROTOTYPES
#define VK_NO_PROTOTYPES
#endif
#include <vulkan/vulkan.h>
#ifdef __cplusplus
extern "C" {{
#endif
VkResult volkInitialize(void);
void volkInitializeCustom(PFN_vkGetInstanceProcAddr handler);
void volkLoadInstance(VkInstance instance);
{guarded(lambda n: f"extern PFN_{n} {n};")}
#ifdef __cplusplus
}}
#endif
'''
    source = f'''// Generated by tools/gen_vk_loader.py. Do not edit.
#include "volk.h"
#if defined(_WIN32)
#include <windows.h>
#else
#include <dlfcn.h>
#endif
#include <stddef.h>

{guarded(lambda n: f"PFN_{n} {n};")}

static void load_global(void)
{{
{chr(10).join(f'    {n} = (PFN_{n})vkGetInstanceProcAddr(NULL, "{n}");' for n in GLOBAL if n in names)}
}}

void volkInitializeCustom(PFN_vkGetInstanceProcAddr handler)
{{
    vkGetInstanceProcAddr = handler;
    load_global();
}}

VkResult volkInitialize(void)
{{
#if defined(_WIN32)
    HMODULE module = LoadLibraryA("vulkan-1.dll");
    if (!module) return VK_ERROR_INITIALIZATION_FAILED;
    PFN_vkGetInstanceProcAddr handler = (PFN_vkGetInstanceProcAddr)(void (*)(void))GetProcAddress(module, "vkGetInstanceProcAddr");
#else
#if defined(__APPLE__)
    static const char *const names[] = {{"libvulkan.dylib", "libvulkan.1.dylib", "libMoltenVK.dylib"}};
#else
    static const char *const names[] = {{"libvulkan.so.1", "libvulkan.so"}};
#endif
    void *module = NULL;
    for (size_t i = 0; i < sizeof(names) / sizeof(names[0]) && !module; ++i)
        module = dlopen(names[i], RTLD_NOW | RTLD_LOCAL);
    if (!module) return VK_ERROR_INITIALIZATION_FAILED;
    PFN_vkGetInstanceProcAddr handler = (PFN_vkGetInstanceProcAddr)dlsym(module, "vkGetInstanceProcAddr");
#endif
    if (!handler) return VK_ERROR_INITIALIZATION_FAILED;
    volkInitializeCustom(handler);
    return VK_SUCCESS;
}}

void volkLoadInstance(VkInstance instance)
{{
{guarded(lambda n: f'    {n} = (PFN_{n})vkGetInstanceProcAddr(instance, "{n}");' if n not in GLOBAL and n != 'vkGetInstanceProcAddr' else f'    /* {n}: loaded globally */')}
}}
'''
    return {'volk.h': header, 'volk.c': source}, names


def main():
    files, names = render()
    if '--check' in sys.argv:
        stale = [n for n, text in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != text]
        if stale: sys.exit('stale generated loader: ' + ', '.join(stale) + ' (run tools/gen_vk_loader.py)')
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f'{len(names)} Vulkan functions')


if __name__ == '__main__':
    main()
